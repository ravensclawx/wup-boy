#!/usr/bin/env python3
"""WUP Boy's test game, written here (no one else's code or pictures): a striped pattern that scrolls, so the picture,
the pause screen, rewind and fast forward can be seen working in wup-emu. For tests only: WUP Boy comes without
games.      python3 testrom.py > "Test Pattern.gb" """
import sys
rom = bytearray(0x8000)
rom[0x100:0x104] = bytes([0x00, 0xC3, 0x50, 0x01])            # nop; jp 0x150
rom[0x134:0x138] = b'TEST'
code = bytes([
    0xF3, 0x31, 0xFE, 0xFF,                                    # di; ld sp, 0xfffe
    0xF0, 0x44, 0xFE, 0x90, 0x20, 0xFA,                        # wait for line 144
    0xAF, 0xE0, 0x40,                                          # the LCD off
    0x21, 0x10, 0x80, 0x06, 0x08,                              # hl = 0x8010 (tile 1), b = 8
    0x3E, 0xF0, 0x22, 0x3E, 0x0F, 0x22, 0x05, 0x20, 0xF7,      # its 8 rows: 0xF0, 0x0F
    0x21, 0x00, 0x98, 0x01, 0x00, 0x04,                        # hl = 0x9800 (the map), bc = 0x400
    0x7D, 0xE6, 0x01, 0x22, 0x0B, 0x78, 0xB1, 0x20, 0xF7,      # tiles 0, 1, 0, 1...
    0x3E, 0xE4, 0xE0, 0x47, 0x3E, 0x91, 0xE0, 0x40,            # the palette; the LCD on
    0xF0, 0x44, 0xFE, 0x90, 0x20, 0xFA,                        # loop: wait for line 144
    0xF0, 0x43, 0x3C, 0xE0, 0x43,                              # scroll one pixel
    0xF0, 0x44, 0xFE, 0x91, 0x20, 0xFA,                        # wait for line 145
    0x18, 0xED,                                                # again
])
rom[0x150:0x150 + len(code)] = code
x = 0
for i in range(0x134, 0x14D): x = (x - rom[i] - 1) & 255      # the header's checksum
rom[0x14D] = x
sys.stdout.buffer.write(rom)
